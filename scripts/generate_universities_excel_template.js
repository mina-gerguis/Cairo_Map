function generateExcelAndCsv() {
  const baseDir = path.resolve(__dirname, "..");
  const xlsxOutPath = path.join(baseDir, "Directions_Routes_Template.xlsx");
  const xlsxPublicPath = path.join(baseDir, "public", "Directions_Routes_Template.xlsx");
  const xlsxUniversitiesPath = path.join(baseDir, "supabase", "Directions_Routes_Universities_10th.xlsx");
  const csvUniversitiesPath = path.join(baseDir, "supabase", "Directions_Routes_Universities_10th.csv");

  const formattedRows = routesData.map((r, idx) => ({
    "م": idx + 1,
    "نقطة البداية": r.from,
    "الوجهة": r.to,
    "نوع وسيلة المواصلات": r.type,
    "اسم وسيلة المواصلات": r.typeName,
    "الأجرة (ج.م)": r.cost,
    "المدة الزمنية": r.duration,
    "مراحل وخطوات المسار": r.legsFormatted,
    "كلمات بديلة للبداية": r.fromAliases,
    "كلمات بديلة للوجهة": r.toAliases,
    "نصيحة ذهبية للمسافرين": r.tips,
    "رابط خريطة Google": r.mapLink
  }));

  // 1. Create Excel Workbook
  const worksheet = XLSX.utils.json_to_sheet(formattedRows);

  worksheet["!cols"] = [
    { wch: 6 },  // م
    { wch: 18 }, // نقطة البداية
    { wch: 25 }, // الوجهة
    { wch: 20 }, // نوع وسيلة المواصلات
    { wch: 32 }, // اسم وسيلة المواصلات
    { wch: 14 }, // الأجرة (ج.م)
    { wch: 20 }, // المدة الزمنية
    { wch: 75 }, // مراحل وخطوات المسار
    { wch: 35 }, // كلمات بديلة للبداية
    { wch: 35 }, // كلمات بديلة للوجهة
    { wch: 40 }, // نصيحة ذهبية للمسافرين
    { wch: 25 }  // رابط خريطة Google
  ];

  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, "نموذج_مسارات_المواصلات");

  // Save to multiple convenient places
  XLSX.writeFile(workbook, xlsxOutPath);
  console.log("✅ Created Excel at:", xlsxOutPath);

  try {
    if (!fs.existsSync(path.join(baseDir, "public"))) {
      fs.mkdirSync(path.join(baseDir, "public"), { recursive: true });
    }
    XLSX.writeFile(workbook, xlsxPublicPath);
    console.log("✅ Created Excel at:", xlsxPublicPath);
  } catch (e) {}

  XLSX.writeFile(workbook, xlsxUniversitiesPath);
  console.log("✅ Created Excel at:", xlsxUniversitiesPath);

  // 2. Also write CSV with UTF-8 BOM
  const csvContent = XLSX.utils.sheet_to_csv(worksheet);
  fs.writeFileSync(csvUniversitiesPath, "\uFEFF" + csvContent, { encoding: "utf8" });
  console.log("✅ Created CSV at:", csvUniversitiesPath);

  console.log(`\n🎉 Done! Generated ${routesData.length} university routes in exact template format.`);
}

generateExcelAndCsv();
