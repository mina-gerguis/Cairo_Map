-- =========================================================================
-- Supabase Schema & Seed Data for Highways and Road News (معلومات الطرق وأخبار الطرق)
-- =========================================================================

-- 1. Create highways_info table
CREATE TABLE IF NOT EXISTS public.highways_info (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    code TEXT,
    type TEXT NOT NULL DEFAULT 'صحراوي', -- حر، صحراوي، ساحلي، زراعي، دائري، محور
    length_km NUMERIC NOT NULL DEFAULT 0,
    start_point TEXT NOT NULL,
    end_point TEXT NOT NULL,
    governorates JSONB NOT NULL DEFAULT '[]'::jsonb,
    speed_private_car INTEGER NOT NULL DEFAULT 120,
    speed_minibus INTEGER NOT NULL DEFAULT 100,
    speed_microbus INTEGER NOT NULL DEFAULT 100,
    speed_pickup INTEGER NOT NULL DEFAULT 90,
    speed_bus INTEGER NOT NULL DEFAULT 100,
    speed_truck INTEGER NOT NULL DEFAULT 80,
    lanes_count INTEGER DEFAULT 4,
    toll_gates JSONB NOT NULL DEFAULT '[]'::jsonb,
    gas_stations JSONB NOT NULL DEFAULT '[]'::jsonb,
    emergency_phone TEXT DEFAULT '01221110000',
    lat NUMERIC DEFAULT 30.0444,
    lng NUMERIC DEFAULT 31.2357,
    status TEXT DEFAULT 'open', -- open, maintenance, fog_warning, detour
    description TEXT,
    radar_info TEXT,
    map_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 2. Create road_news table
CREATE TABLE IF NOT EXISTS public.road_news (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title TEXT NOT NULL,
    summary TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'general', -- weather_fog, maintenance, detour, traffic, radar, general
    severity TEXT NOT NULL DEFAULT 'info', -- critical, warning, info
    road_name TEXT DEFAULT 'كافة الطرق',
    source TEXT DEFAULT 'الإدارة العامة للمرور',
    published_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Enable RLS
ALTER TABLE public.highways_info ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.road_news ENABLE ROW LEVEL SECURITY;

-- Select policies (Public Read)
CREATE POLICY "Anyone can view highways_info" ON public.highways_info FOR SELECT USING (true);
CREATE POLICY "Anyone can view road_news" ON public.road_news FOR SELECT USING (true);

-- Manage policies (Admin Write/Update/Delete)
CREATE POLICY "Admins can manage highways_info" ON public.highways_info 
    FOR ALL USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND is_admin = true));

CREATE POLICY "Admins can manage road_news" ON public.road_news 
    FOR ALL USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND is_admin = true));

