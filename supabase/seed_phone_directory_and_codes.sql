-- 1. التأكد من إنشاء جدول دليل الهاتف phone_directory
CREATE TABLE IF NOT EXISTS public.phone_directory (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    specialty TEXT NOT NULL,
    phone_number TEXT NOT NULL,
    logo_url TEXT DEFAULT '',
    icon TEXT DEFAULT 'bx bx-phone',
    description TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- التأكد من وجود عمود description
ALTER TABLE public.phone_directory ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE public.phone_directory ADD COLUMN IF NOT EXISTS icon TEXT DEFAULT 'bx bx-phone';
ALTER TABLE public.phone_directory ADD COLUMN IF NOT EXISTS logo_url TEXT DEFAULT '';

-- تفعيل RLS وسياسات الأمان لدليل الهاتف
ALTER TABLE public.phone_directory ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone can view phone_directory" ON public.phone_directory;
CREATE POLICY "Anyone can view phone_directory" ON public.phone_directory FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admins can manage phone_directory" ON public.phone_directory;
CREATE POLICY "Admins can manage phone_directory" ON public.phone_directory FOR ALL 
USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND is_admin = true));


-- 2. التأكد من إنشاء جدول أكواد الاتصالات telecom_codes
CREATE TABLE IF NOT EXISTS public.telecom_codes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    company TEXT NOT NULL,
    section_name TEXT NOT NULL,
    title TEXT NOT NULL,
    code TEXT NOT NULL,
    icon TEXT DEFAULT 'bx bx-bookmark',
